def load_system_translations(locale):
    """Extract available official translations from Omarchy system catalogs."""
    sh_path = os.path.join(SYSTEM_I18N_DIR, locale, "shell.json")
    menu_path = os.path.join(SYSTEM_I18N_DIR, locale, "menu.json")
    sh = {}
    menu = {}
    if os.path.exists(sh_path):
        try:
            with open(sh_path, "r", encoding="utf-8") as f:
                sh = json.load(f)
        except Exception:
            pass
    if os.path.exists(menu_path):
        try:
            with open(menu_path, "r", encoding="utf-8") as f:
                menu = json.load(f)
        except Exception:
            pass

    t = {}
    if "dock.positionLeft" in sh:
        t["picker.left"] = sh["dock.positionLeft"]
    if "dock.positionRight" in sh:
        t["picker.right"] = sh["dock.positionRight"]
    if "dock.autoHide" in sh:
        t["dock.autohide"] = sh["dock.autoHide"]
    if "apps" in menu and isinstance(menu["apps"], dict):
        t["picker.apps"] = menu["apps"].get("label")
    if "appearance.dock" in menu and isinstance(menu["appearance.dock"], dict):
        lbl = menu["appearance.dock"].get("label")
        if lbl:
            t["picker.dock"] = lbl
            t["dock.title"] = lbl
    if "appearance.dock.autohide" in menu and isinstance(menu["appearance.dock.autohide"], dict):
        lbl = menu["appearance.dock.autohide"].get("label")
        if lbl:
            t["dock.autohide"] = lbl
    if "system" in menu and isinstance(menu["system"], dict):
        lbl = menu["system"].get("label")
        if lbl:
            t["folder.system"] = lbl
    if "trigger.share.file" in menu and isinstance(menu["trigger.share.file"], dict):
        lbl = menu["trigger.share.file"].get("label")
        if lbl:
            t["folder.files"] = lbl
    if "appearance.top-bar.indicators.clock" in menu and isinstance(menu["appearance.top-bar.indicators.clock"], dict):
        lbl = menu["appearance.top-bar.indicators.clock"].get("label")
        if lbl:
            t["widget.clock"] = lbl
    if "appearance.top-bar.indicators" in menu and isinstance(menu["appearance.top-bar.indicators"], dict):
        lbl = menu["appearance.top-bar.indicators"].get("label")
        if lbl:
            t["widget.indicators"] = lbl
    return t

