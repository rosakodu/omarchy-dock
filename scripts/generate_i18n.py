def generate_all():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(LOCALES_PATH, "r", encoding="utf-8") as f:
        locales = json.load(f)

    print(f"Generating catalogs for {len(locales)} locales...")

    for loc in locales.keys():
        catalog = ENGLISH_BASE.copy()

        # Check regional base fallback (e.g. pt-BR -> pt)
        if "-" in loc:
            base_lang = loc.split("-")[0]
            if base_lang in LOCALE_DICTIONARIES:
                catalog.update(LOCALE_DICTIONARIES[base_lang])

        # Check direct locale translations
        if loc in LOCALE_DICTIONARIES:
            catalog.update(LOCALE_DICTIONARIES[loc])

        # Overlay official system translations from Omarchy
        system_t = load_system_translations(loc)
        for k, v in system_t.items():
            if v:
                catalog[k] = v

        # Apply CLDR plural forms
        if loc in PLURAL_TEMPLATES:
            catalog["dock.items"] = PLURAL_TEMPLATES[loc]
        elif "-" in loc and loc.split("-")[0] in PLURAL_TEMPLATES:
            catalog["dock.items"] = PLURAL_TEMPLATES[loc.split("-")[0]]
        else:
            catalog["dock.items"] = {"one": "%1 item", "other": "%1 items"}

        # Write catalog JSON
        target_path = os.path.join(OUTPUT_DIR, f"{loc}.json")
        with open(target_path, "w", encoding="utf-8") as f:
            json.dump(catalog, f, ensure_ascii=False, indent=2)

    print(f"Successfully generated all {len(locales)} localization catalogs in {OUTPUT_DIR}!")

if __name__ == "__main__":
    generate_all()
